#!/usr/bin/env bash
# Opt-in integration test: a privileged, disposable nested Swarm on the local default daemon.
# Fixture data and private evidence remain in /tmp; the nested daemon and volumes are removed.
set -euo pipefail
umask 077
infra_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
source_tag=${PGE2E_SOURCE_TAG:-17.11-alpine}
target_tag=${PGE2E_TARGET_TAG:-18-alpine}
fixture=$(mktemp -d /tmp/razcloud-postgres-e2e.XXXXXXXX)
name=razcloud-postgres-e2e-${fixture##*.}
outer() { env -u DOCKER_CONTEXT -u DOCKER_HOST docker --context default "$@"; }
cleanup() { outer container rm --force --volumes "$name" >/dev/null 2>&1 || true; }
trap cleanup EXIT
trap 'exit 130' INT TERM
printf 'Fixture directory: %s\n' "$fixture"
outer run --privileged --detach --name "$name" -e DOCKER_TLS_CERTDIR= -p 127.0.0.1::2375 docker:29-dind --storage-driver=overlay2 >/dev/null
export PGE2E_DOCKER_HOST=tcp://$(outer port "$name" 2375/tcp)
export PGE2E_LOG_DIR="$fixture"
cat > "$fixture/docker" <<'SH'
#!/usr/bin/env bash
set -euo pipefail
[[ "$1" == --context && "$2" == postgres-e2e ]]
shift 2
# Capture fixture-only upgrader diagnostics; no control-plane or data responses are mocked.
if [[ "$1" == service && "$2" == create ]]; then
  args=("$@")
  for ((j=0; j<${#args[@]}-1; j++)); do
    if [[ "${args[j]}" == --log-driver ]]; then args[j+1]=json-file; fi
  done
  set -- "${args[@]}"
fi
if [[ "$1" == service && "$2" == rm ]]; then
  env -u DOCKER_CONTEXT -u DOCKER_HOST docker --host "$PGE2E_DOCKER_HOST" service logs "$3" > "$PGE2E_LOG_DIR/upgrader-debug.log" 2>&1 || true
fi
exec env -u DOCKER_CONTEXT -u DOCKER_HOST docker --host "$PGE2E_DOCKER_HOST" "$@"
SH
chmod 700 "$fixture/docker"
inner() { "$fixture/docker" --context postgres-e2e "$@"; }
ready=false
for ((i=0; i<90; i++)); do
  if inner info >/dev/null 2>&1; then ready=true; break; fi
  sleep 1
done
if [[ "$ready" != true ]]; then outer logs "$name"; exit 1; fi
inner swarm init --advertise-addr eth0 >/dev/null
for image in "postgres:$source_tag" "postgres:$target_tag" "pgautoupgrade/pgautoupgrade:$target_tag" caddy:2-alpine; do
  printf 'Pulling fixture image %s\n' "$image"
  inner image pull "$image" > "$fixture/${image//\//_}.pull.log" 2>&1
done
printf 'fixture-only-password' | inner secret create postgres_password - >/dev/null
inner volume create pge2e-postgres >/dev/null
inner service create --detach=true --name pge2e_postgres --label com.docker.stack.namespace=pge2e --replicas 1 --mount type=volume,source=pge2e-postgres,target=/var/lib/postgresql/data --secret source=postgres_password,target=postgres_password --env POSTGRES_USER=razcloud --env POSTGRES_DB=razcloud --env POSTGRES_PASSWORD_FILE=/run/secrets/postgres_password "postgres:$source_tag" >/dev/null
inner service create --detach=true --name pge2e_caddy-docker-proxy --label com.docker.stack.namespace=pge2e --replicas 1 caddy:2-alpine >/dev/null
container_id() { inner ps --filter label=com.docker.swarm.service.name=pge2e_postgres --format '{{.ID}}'; }
wait_sql() {
  local container="$1"
  for ((i=0; i<120; i++)); do
    if inner exec "$container" psql -XAtw -U razcloud -d razcloud -c 'SELECT 1' >/dev/null 2>&1; then return; fi
    sleep 1
  done
  inner logs "$container"
  return 1
}
pg=''
for ((i=0; i<120; i++)); do pg=$(container_id); [[ -z "$pg" ]] || break; sleep 1; done
[[ -n "$pg" ]]
wait_sql "$pg"
printf 'Creating real PostgreSQL 17 fixtures\n'
inner exec -i "$pg" psql -X -v ON_ERROR_STOP=1 -U razcloud -d razcloud > "$fixture/seed.log" <<'SQL'
CREATE ROLE fixture_app LOGIN PASSWORD 'fixture-app-password';
CREATE DATABASE fixture_app OWNER fixture_app;
CREATE TABLE instances (instance_name text PRIMARY KEY, db_name text NOT NULL, db_user text NOT NULL, db_password text NOT NULL);
INSERT INTO instances VALUES ('fixture_app', 'fixture_app', 'fixture_app', 'fixture-app-password');
SQL
inner exec -i "$pg" psql -X -v ON_ERROR_STOP=1 -U fixture_app -d fixture_app >> "$fixture/seed.log" <<'SQL'
CREATE EXTENSION pgcrypto;
CREATE TABLE accounts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username text UNIQUE NOT NULL,
 settings jsonb NOT NULL,
 body text NOT NULL,
 secret bytea NOT NULL,
 created_at timestamptz NOT NULL DEFAULT '2026-01-02 03:04:05+00',
 search tsvector GENERATED ALWAYS AS (to_tsvector('simple', body)) STORED
);
CREATE INDEX account_search_idx ON accounts USING gin(search);
CREATE INDEX account_settings_idx ON accounts USING gin(settings);
INSERT INTO accounts(username, settings, body, secret)
 SELECT 'user-'||i, jsonb_build_object('number',i,'name','árvíztűrő'), repeat('payload-'||i||' λ ',500), digest(i::text,'sha256')
 FROM generate_series(1,1000) i;
CREATE TABLE events (
 id bigserial PRIMARY KEY,
 account_id bigint NOT NULL REFERENCES accounts(id),
 amount numeric(12,2) NOT NULL CHECK (amount >= 0),
 description text NOT NULL
);
INSERT INTO events(account_id, amount, description)
 SELECT (i % 1000)+1, i / 100.0, 'event-'||i FROM generate_series(1,10000) i;
CREATE VIEW totals AS SELECT account_id, sum(amount) AS total FROM events GROUP BY account_id;
SQL
cat > "$fixture/fingerprint.sql" <<'SQL'
SELECT 'accounts', count(*), md5(string_agg(row_to_json(a)::text, E'\n' ORDER BY id)) FROM accounts a;
SELECT 'events', count(*), md5(string_agg(row_to_json(e)::text, E'\n' ORDER BY id)) FROM events e;
SELECT 'totals', count(*), md5(string_agg(row_to_json(t)::text, E'\n' ORDER BY account_id)) FROM totals t;
SELECT 'search', count(*) FROM accounts WHERE search @@ to_tsquery('simple', 'payload');
SELECT 'account-sequence',last_value,is_called FROM accounts_id_seq;
SELECT 'event-sequence',last_value,is_called FROM events_id_seq;
SELECT 'owner', tableowner FROM pg_tables WHERE schemaname='public' ORDER BY tablename;
SELECT 'constraints', contype, count(*) FROM pg_constraint WHERE connamespace='public'::regnamespace AND contype IN ('c','f','p','u') GROUP BY contype ORDER BY contype;
SELECT 'not-null',attrelid::regclass,attname,attnotnull FROM pg_attribute WHERE attrelid IN ('accounts'::regclass,'events'::regclass) AND attnum>0 AND NOT attisdropped ORDER BY attrelid::regclass::text,attnum;
SELECT 'indexes', indexname, indexdef FROM pg_indexes WHERE schemaname='public' ORDER BY indexname;
SQL
fingerprint() {
  local container="$1"
  inner exec -i "$container" psql -XAtw -v ON_ERROR_STOP=1 -U fixture_app -d fixture_app < "$fixture/fingerprint.sql"
  inner exec "$container" psql -XAtw -U razcloud -d razcloud -c "SELECT instance_name,db_name,db_user,md5(db_password) FROM instances ORDER BY instance_name; SELECT rolname,rolcanlogin,rolsuper,md5(rolpassword) FROM pg_authid WHERE rolname IN ('razcloud','fixture_app') ORDER BY rolname"
}
fingerprint "$pg" > "$fixture/before.txt"
cat > "$fixture/test.env" <<ENV
DOCKER_CONTEXT=postgres-e2e
DOCKER_CLI=$fixture/docker
STACK_NAME=pge2e
POSTGRES_IMAGE_TAG=$target_tag
POSTGRES_VOLUME_TARGET=/var/lib/postgresql
POSTGRES_BACKUP_DIR=$fixture/backups
POSTGRES_UPGRADE_TIMEOUT=300
ENV
printf 'Running the real make postgres-upgrade target\n'
set +e
GOCACHE=${GOCACHE:-$fixture/go-cache} make -C "$infra_dir" postgres-upgrade ENV_FILE="$fixture/test.env" 2>&1 | tee "$fixture/upgrade.log"
status=${PIPESTATUS[0]}
set -e
if [[ ${PGE2E_EXPECT_PREFLIGHT_FAILURE:-no} == yes ]]; then
  [[ "$status" != 0 ]]
  grep -q 'newer than final destination\|older than running PostgreSQL' "$fixture/upgrade.log"
  pg=$(container_id)
  fingerprint "$pg" > "$fixture/after.txt"
  diff -u "$fixture/before.txt" "$fixture/after.txt"
  inner service ls --format '{{.Name}} {{.Replicas}}' > "$fixture/services.txt"
  grep -q '^pge2e_caddy-docker-proxy 1/1$' "$fixture/services.txt"
  grep -q '^pge2e_postgres 1/1$' "$fixture/services.txt"
  printf 'PASS: incompatible published images rejected before downtime; PostgreSQL 17 tables and roles unchanged.\nEvidence: %s\n' "$fixture"
  exit 0
fi
[[ "$status" == 0 ]]
pg=$(container_id)
wait_sql "$pg"
inner exec "$pg" psql -XAtw -U razcloud -d razcloud -c 'SELECT version()'
fingerprint "$pg" > "$fixture/after.txt"
diff -u "$fixture/before.txt" "$fixture/after.txt"
inner exec -i "$pg" psql -XAtw -v ON_ERROR_STOP=1 -U fixture_app -d fixture_app > "$fixture/post-upgrade-checks.txt" <<'SQL'
DO $$ BEGIN
 BEGIN INSERT INTO accounts(username,settings,body,secret) VALUES ('user-1','{}','duplicate','\x00'); RAISE EXCEPTION 'unique constraint missing'; EXCEPTION WHEN unique_violation THEN NULL; END;
 BEGIN INSERT INTO events(account_id,amount,description) VALUES (999999,1,'bad fk'); RAISE EXCEPTION 'foreign key missing'; EXCEPTION WHEN foreign_key_violation THEN NULL; END;
 BEGIN INSERT INTO events(account_id,amount,description) VALUES (1,-1,'bad amount'); RAISE EXCEPTION 'check constraint missing'; EXCEPTION WHEN check_violation THEN NULL; END;
END $$;
INSERT INTO accounts(username,settings,body,secret) VALUES ('after-upgrade','{}','payload new','\x00') RETURNING id;
SELECT encode(digest('extension still works','sha256'),'hex');
SQL
inner exec --env PGPASSWORD=fixture-app-password "$pg" psql -XAtw -h 127.0.0.1 -U fixture_app -d fixture_app -c 'SELECT count(*) FROM accounts' > "$fixture/password-login.txt"
inner service ls --format '{{.Name}} {{.Replicas}}' > "$fixture/services.txt"
grep -q '^pge2e_caddy-docker-proxy 1/1$' "$fixture/services.txt"
grep -q '^pge2e_postgres 1/1$' "$fixture/services.txt"
printf 'Restoring the downloaded cold archive into a separate PostgreSQL 17 volume\n'
archives=("$fixture"/backups/*/postgres.tar.gz)
[[ ${#archives[@]} == 1 && -f "${archives[0]}" ]]
inner volume create pge2e-restored >/dev/null
inner run --rm -i --network none --mount type=volume,source=pge2e-restored,target=/restore --entrypoint tar "postgres:$source_tag" -xzpf - -C /restore < "${archives[0]}"
restore=$(inner run --detach --name pge2e-restore --network none --mount type=volume,source=pge2e-restored,target=/var/lib/postgresql/data --env POSTGRES_USER=razcloud "postgres:$source_tag")
wait_sql "$restore"
fingerprint "$restore" > "$fixture/restored.txt"
diff -u "$fixture/before.txt" "$fixture/restored.txt"
printf 'PASS: real Make target upgraded 1000 accounts and 10000 events; data, roles, ownership, indexes and constraints match; PostgreSQL 17 cold archive restores correctly.\nEvidence: %s\n' "$fixture"
